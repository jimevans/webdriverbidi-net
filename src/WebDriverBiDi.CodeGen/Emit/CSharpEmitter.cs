    private static (string RelativePath, string Code) EmitEnum(EnumDef e, EmitContext ctx)
    {
        string csharpName = ctx.ResolveClassName(e.AstNode.Name, NamingConventions.LocalName(e.AstNode.Name));
        string ns = NamingConventions.Namespace(e.AstNode.Name);
        string subdir = NamingConventions.Subdir(e.AstNode.Name);
        string fileName = csharpName + ".cs";
        string relativePath = subdir.Length > 0 ? $"{subdir}/{fileName}" : fileName;

        StringBuilder sb = new();
        sb.AppendFormat(CopyrightHeader, fileName);
        sb.AppendLine();
        sb.AppendLine($"namespace {ns};");
        sb.AppendLine();
        sb.AppendLine("using System.Text.Json.Serialization;");
        sb.AppendLine("using WebDriverBiDi.JsonConverters;");
        sb.AppendLine();
        sb.AppendLine($"[JsonConverter(typeof(EnumValueJsonConverter<{csharpName}>))]");
        sb.AppendLine($"public enum {csharpName}");
        sb.AppendLine("{");

        for (int i = 0; i < e.Values.Count; i++)
        {
            string jsonValue = e.Values[i];
            string memberName = NamingConventions.EnumMemberName(jsonValue);
            if (NamingConventions.NeedsJsonEnumValueAttr(memberName, jsonValue))
            {
                sb.AppendLine($"    [JsonEnumValue(\"{EscapeString(jsonValue)}\")]");
            }

            sb.AppendLine($"    {memberName},");
            if (i < e.Values.Count - 1)
            {
                sb.AppendLine();
            }
        }

        sb.AppendLine("}");
        return (relativePath, sb.ToString());
    }


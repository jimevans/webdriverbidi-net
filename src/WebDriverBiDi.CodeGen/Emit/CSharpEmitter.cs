    // -----------------------------------------------------------------------
    // Using directives
    // -----------------------------------------------------------------------
    private static IReadOnlyList<string> GatherUsings(
        List<PropSpec> props,
        string currentNamespace,
        bool isCommandParams)
    {
        SortedSet<string> usings = new()
        {
            "System.Text.Json.Serialization",
        };

        foreach (PropSpec p in props)
        {
            foreach (string cddlName in p.ReferencedCddlNames)
            {
                string typeNs = NamingConventions.Namespace(cddlName);

                // Skip same namespace and root WebDriverBiDi namespace (accessible without a using
                // from any child namespace like WebDriverBiDi.Script due to C# namespace scoping)
                if (typeNs != currentNamespace && typeNs != "WebDriverBiDi")
                {
                    usings.Add(typeNs);
                }
            }
        }

        return usings.ToList();
    }

    private static void AppendUsings(StringBuilder sb, IReadOnlyList<string> usings)
    {
        foreach (string u in usings)
        {
            sb.AppendLine($"using {u};");
        }

        sb.AppendLine();
    }

    // -----------------------------------------------------------------------
    // Helpers
    // -----------------------------------------------------------------------
    private static bool IsEmptyResult(CommandResultDef r) =>
        r.AstNode is AstVariableNode v &&
        v.PropertyType.Count == 1 &&
        v.PropertyType[0] is AstTypeGroupRef { Value: "EmptyResult" };

    private static string PascalCase(string name) =>
        string.IsNullOrEmpty(name) ? name
            : char.ToUpperInvariant(name[0]) + name[1..];

    private static string CamelCase(string name) =>
        string.IsNullOrEmpty(name) ? name
            : char.ToLowerInvariant(name[0]) + name[1..];

    private static string EscapeString(string value)
        => value.Replace("\\", "\\\\").Replace("\"", "\\\"");


    /// <summary>
    /// Returns all files to generate, as a sequence of (relative output path, source text) pairs.
    /// The relative path is relative to the --out root (e.g. "Browser/CloseCommandResult.cs").
    /// </summary>
    /// <param name="model">The semantic model to emit from.</param>
    /// <param name="byName">The map of CDDL name → AST node, for reference when resolving types.</param>
    /// <param name="config">Optional generator configuration (skip lists, overrides, etc.).</param>
    /// <returns>A sequence of (relative output path, source text) pairs.</returns>
    public static IEnumerable<(string RelativePath, string Source)> Emit(SpecModel model, IReadOnlyDictionary<string, AstNode> byName, GeneratorConfig? config = null)
    {
        EmitContext ctx = new(config);

        // ---- Phase 3 ----
        foreach (EnumDef e in model.Enums)
        {
            if (ctx.SkipSet.Contains(e.AstNode.Name))
            {
                continue;
            }

            yield return EmitEnum(e, ctx);
        }

        foreach (CommandResultDef r in model.CommandResults)
        {
            if (ctx.SkipSet.Contains(r.AstNode.Name))
            {
                continue;
            }

            if (IsEmptyResult(r))
            {
                yield return EmitEmptyResultCommandResult(r, ctx);
            }
        }

        foreach (CommandDef cmd in model.Commands)
        {
            if (ctx.SkipSet.Contains(cmd.AstNode.Name))
            {
                continue;
            }

            if (cmd.ParamsTypeName == "EmptyParams")
            {
                yield return EmitEmptyParamsCommandParameters(cmd, ctx);
            }
        }

        // ---- Phase 4 ----

        // Group command results (have their own fields)
        foreach (CommandResultDef r in model.CommandResults)
        {
            if (ctx.SkipSet.Contains(r.AstNode.Name))
            {
                continue;
            }

            if (r.AstNode is AstGroupNode resultGroup)
            {
                yield return EmitGroupCommandResult(r, resultGroup, model, byName, ctx);
            }
        }

        // Command parameters with non-empty params types
        foreach (CommandDef cmd in model.Commands)
        {
            if (ctx.SkipSet.Contains(cmd.AstNode.Name))
            {
                continue;
            }

            if (cmd.ParamsTypeName != "EmptyParams" &&
                byName.TryGetValue(cmd.ParamsTypeName, out AstNode? paramsNode) &&
                paramsNode is AstGroupNode paramsGroup)
            {
                yield return EmitCommandParameters(cmd, paramsGroup, model, byName, ctx);
            }
        }

        // Event args
        foreach (EventDef evt in model.Events)
        {
            if (ctx.SkipSet.Contains(evt.AstNode.Name))
            {
                continue;
            }

            if (byName.TryGetValue(evt.ParamsTypeName, out AstNode? evtParamsNode) &&
                evtParamsNode is AstGroupNode evtParamsGroup)
            {
                yield return EmitEventArgs(evt, evtParamsGroup, model, byName, ctx);
            }
        }

        // ---- Phase 5 ----

        // Build reverse map: member CDDL name → single union CDDL name
        // Members appearing in multiple unions are excluded (can't have multiple base classes)
        IReadOnlyDictionary<string, string> memberToUnion = BuildMemberToUnionMap(model.DiscriminatedUnions);

        // Collect data classes transitively reachable from command params (need public setters)
        IReadOnlySet<string> paramsReachable = CollectParamsReachableTypes(model, byName);

        // Discriminated union abstract base classes
        foreach (DiscriminatedUnionDef u in model.DiscriminatedUnions)
        {
            if (ctx.SkipSet.Contains(u.AstNode.Name))
            {
                continue;
            }

            yield return EmitDiscriminatedUnion(u, model.NodeKinds, ctx);
        }

        // Data classes (with union base class where applicable)
        foreach (DataClassDef d in model.DataClasses)
        {
            if (ctx.SkipSet.Contains(d.AstNode.Name))
            {
                continue;
            }

            yield return EmitDataClass(d, model, byName, memberToUnion, paramsReachable, ctx);
        }
    }


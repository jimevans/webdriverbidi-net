    /// <summary>
    /// Builds a map from each union member CDDL name to its union's CDDL name,
    /// but only for members that belong to exactly one union.
    /// Members in multiple unions are excluded (can't be given a single base class).
    /// </summary>
    private static IReadOnlyDictionary<string, string> BuildMemberToUnionMap(IReadOnlyList<DiscriminatedUnionDef> unions)
    {
        // Count how many unions each member name appears in
        Dictionary<string, int> counts = new(StringComparer.Ordinal);
        foreach (DiscriminatedUnionDef u in unions)
        {
            foreach (string m in u.MemberTypeNames)
            {
                counts[m] = counts.TryGetValue(m, out int c) ? c + 1 : 1;
            }
        }

        Dictionary<string, string> result = new(StringComparer.Ordinal);
        foreach (DiscriminatedUnionDef u in unions)
        {
            foreach (string m in u.MemberTypeNames)
            {
                if (counts[m] == 1)
                {
                    result[m] = u.AstNode.Name;
                }
            }
        }

        return result;
    }

    /// <summary>
    /// Walks the type graph transitively from all command parameter types and returns
    /// the set of data class CDDL names that are reachable from them.
    /// These types need public setters and constructors so callers can construct instances.
    /// </summary>
    private static IReadOnlySet<string> CollectParamsReachableTypes(SpecModel model, IReadOnlyDictionary<string, AstNode> byName)
    {
        Queue<string> queue = new();
        HashSet<string> visited = new(StringComparer.Ordinal);

        // Seed with all non-EmptyParams command params type names
        foreach (CommandDef cmd in model.Commands)
        {
            if (cmd.ParamsTypeName != "EmptyParams")
            {
                queue.Enqueue(cmd.ParamsTypeName);
            }
        }

        while (queue.Count > 0)
        {
            string name = queue.Dequeue();
            if (!visited.Add(name))
            {
                continue;
            }

            if (!byName.TryGetValue(name, out AstNode? node))
            {
                continue;
            }

            IEnumerable<string> referencedNames;
            if (node is AstGroupNode group)
            {
                referencedNames = CollectGroupReferencedCddlNames(group, byName);
            }
            else if (node is AstVariableNode variable)
            {
                referencedNames = variable.PropertyType.OfType<AstTypeGroupRef>().Select(r => r.Value);
            }
            else if (node is AstArrayNode array)
            {
                referencedNames = array.Values.SelectMany(e => TypeResolver.ReferencedCddlNames(e.Type));
            }
            else
            {
                continue;
            }

            foreach (string refName in referencedNames)
            {
                if (!visited.Contains(refName))
                {
                    queue.Enqueue(refName);
                }
            }
        }

        return visited
            .Where(name => model.NodeKinds.TryGetValue(name, out NodeKind kind) && kind == NodeKind.DataClass)
            .ToHashSet(StringComparer.Ordinal);
    }

    /// <summary>
    /// Yields all CDDL names directly referenced by a group's property type expressions,
    /// flattening CDDL group inclusions recursively.
    /// </summary>
    private static IEnumerable<string> CollectGroupReferencedCddlNames(
        AstGroupNode group,
        IReadOnlyDictionary<string, AstNode> byName,
        HashSet<string>? groupVisited = null)
    {
        foreach (AstPropertyItem item in group.Properties)
        {
            if (item is not AstPropertyEntry entry)
            {
                continue;
            }

            // CDDL group inclusion — recurse into the referenced group
            if (string.IsNullOrEmpty(entry.Name) &&
                entry.Type.Count == 1 &&
                entry.Type[0] is AstTypeGroupRef gr &&
                gr.Value is not ("Extensible" or "EmptyParams"))
            {
                groupVisited ??= new HashSet<string>(StringComparer.Ordinal);
                if (groupVisited.Add(gr.Value) &&
                    byName.TryGetValue(gr.Value, out AstNode? refNode) &&
                    refNode is AstGroupNode refGroup)
                {
                    foreach (string n in CollectGroupReferencedCddlNames(refGroup, byName, groupVisited))
                    {
                        yield return n;
                    }
                }

                continue;
            }

            // Skip structural fields
            if (entry.Name is "method" or "params" or "id")
            {
                continue;
            }

            foreach (string refName in TypeResolver.ReferencedCddlNames(entry.Type))
            {
                yield return refName;
            }
        }
    }


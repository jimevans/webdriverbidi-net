    // -----------------------------------------------------------------------
    private static (string RelativePath, string Code) EmitEventArgs(
        EventDef evt,
        AstGroupNode paramsGroup,
        SpecModel model,
        IReadOnlyDictionary<string, AstNode> byName,
        EmitContext ctx)
    {
        // Event name: "browsingContext.ContextCreated" → "ContextCreatedEventArgs"
        string csharpName = ctx.ResolveClassName(
            evt.AstNode.Name,
            NamingConventions.LocalName(evt.AstNode.Name) + "EventArgs");
        string ns = NamingConventions.Namespace(evt.AstNode.Name);
        string subdir = NamingConventions.Subdir(evt.AstNode.Name);
        string fileName = csharpName + ".cs";
        string relativePath = subdir.Length > 0 ? $"{subdir}/{fileName}" : fileName;

        List<PropSpec> props = GatherProperties(paramsGroup, evt.ParamsTypeName, byName, model.NodeKinds, ctx);
        IReadOnlyList<string> usings = GatherUsings(props, ns, isCommandParams: false);

        StringBuilder sb = new();
        sb.AppendFormat(CopyrightHeader, fileName);
        sb.AppendLine();
        sb.AppendLine($"namespace {ns};");
        sb.AppendLine();
        AppendUsings(sb, usings);
        sb.AppendLine($"public record {csharpName} : WebDriverBiDiEventArgs");
        sb.AppendLine("{");

        // JsonConstructor with all required fields
        List<PropSpec> allRequired = props.Where(p => p.IsRequired).ToList();
        if (allRequired.Count > 0)
        {
            string ctorParams = string.Join(", ", allRequired.Select(p =>
                p.IsList ? $"List<{p.ListElementType}> {CamelCase(p.CSharpName)}"
                         : $"{p.CSharpType} {CamelCase(p.CSharpName)}"));

            sb.AppendLine("    [JsonConstructor]");
            sb.AppendLine($"    public {csharpName}({ctorParams})");
            sb.AppendLine("    {");
            foreach (PropSpec p in allRequired)
            {
                if (p.IsList)
                {
                    sb.AppendLine($"        this.Serializable{p.CSharpName} = {CamelCase(p.CSharpName)};");
                }
                else
                {
                    sb.AppendLine($"        this.{p.CSharpName} = {CamelCase(p.CSharpName)};");
                }
            }

            sb.AppendLine("    }");
        }
        else
        {
            sb.AppendLine("    [JsonConstructor]");
            sb.AppendLine($"    internal {csharpName}()");
            sb.AppendLine("    {");
            sb.AppendLine("    }");
        }

        sb.AppendLine();
        AppendDeserializationProperties(sb, props);
        sb.AppendLine("}");
        return (relativePath, sb.ToString());
    }

    // -----------------------------------------------------------------------
    // Phase 4: Data class
    // -----------------------------------------------------------------------
    private static (string RelativePath, string Code) EmitDataClass(
        DataClassDef d,
        SpecModel model,
        IReadOnlyDictionary<string, AstNode> byName,
        IReadOnlyDictionary<string, string>? memberToUnion = null,
        IReadOnlySet<string>? paramsReachable = null,
        EmitContext? ctx = null)
    {
        ctx ??= new EmitContext(null);
        string csharpName = ctx.ResolveClassName(d.AstNode.Name, NamingConventions.LocalName(d.AstNode.Name));
        string ns = NamingConventions.Namespace(d.AstNode.Name);
        string subdir = NamingConventions.Subdir(d.AstNode.Name);
        string fileName = csharpName + ".cs";
        string relativePath = subdir.Length > 0 ? $"{subdir}/{fileName}" : fileName;

        List<PropSpec> props = GatherProperties(d.AstNode, d.AstNode.Name, byName, model.NodeKinds, ctx);
        IReadOnlyList<string> usings = GatherUsings(props, ns, isCommandParams: false);

        // Determine base class if this data class is a union member
        string? baseClass = null;
        if (memberToUnion is not null &&
            memberToUnion.TryGetValue(d.AstNode.Name, out string? unionCddlName))
        {
            baseClass = ctx.ResolveClassName(unionCddlName, NamingConventions.LocalName(unionCddlName));
        }

        bool isParamsReachable = paramsReachable is not null &&
            paramsReachable.Contains(d.AstNode.Name);

        StringBuilder sb = new();
        sb.AppendFormat(CopyrightHeader, fileName);
        sb.AppendLine();
        sb.AppendLine($"namespace {ns};");
        sb.AppendLine();
        AppendUsings(sb, usings);
        string classDecl = baseClass is not null
            ? $"public record {csharpName} : {baseClass}"
            : $"public record {csharpName}";
        sb.AppendLine(classDecl);
        sb.AppendLine("{");

        if (isParamsReachable)
        {
            // Params-reachable: public constructor and public setters so callers can construct instances
            sb.AppendLine($"    public {csharpName}()");
            if (baseClass is not null)
            {
                sb.AppendLine("        : base()");
            }

            sb.AppendLine("    {");
            sb.AppendLine("    }");
            sb.AppendLine();
            AppendParamsDataClassProperties(sb, props);
        }
        else
        {
            // Deserialization pattern: [JsonConstructor] internal constructor + internal setters
            sb.AppendLine("    [JsonConstructor]");
            sb.AppendLine($"    internal {csharpName}()");
            if (baseClass is not null)
            {
                sb.AppendLine("        : base()");
            }

            sb.AppendLine("    {");
            sb.AppendLine("    }");
            sb.AppendLine();
            AppendDeserializationProperties(sb, props);
        }

        sb.AppendLine("}");
        return (relativePath, sb.ToString());
    }

    // -----------------------------------------------------------------------
    // Phase 5: Discriminated union abstract base class
    // -----------------------------------------------------------------------
    private static (string RelativePath, string Code) EmitDiscriminatedUnion(
        DiscriminatedUnionDef u,
        IReadOnlyDictionary<string, NodeKind> nodeKinds,
        EmitContext ctx)
    {
        string csharpName = ctx.ResolveClassName(u.AstNode.Name, NamingConventions.LocalName(u.AstNode.Name));
        string ns = NamingConventions.Namespace(u.AstNode.Name);
        string subdir = NamingConventions.Subdir(u.AstNode.Name);
        string fileName = csharpName + ".cs";
        string relativePath = subdir.Length > 0 ? $"{subdir}/{fileName}" : fileName;

        StringBuilder sb = new();
        sb.AppendFormat(CopyrightHeader, fileName);
        sb.AppendLine();
        sb.AppendLine($"namespace {ns};");
        sb.AppendLine();
        sb.AppendLine("using System.Text.Json.Serialization;");
        sb.AppendLine();

        // [JsonDerivedType] for each member
        foreach (string memberCddlName in u.MemberTypeNames)
        {
            string memberCsharp = ResolveMemberTypeName(memberCddlName, nodeKinds, ctx);
            sb.AppendLine($"[JsonDerivedType(typeof({memberCsharp}))]");
        }

        sb.AppendLine($"public abstract record {csharpName}");
        sb.AppendLine("{");
        sb.AppendLine("}");
        return (relativePath, sb.ToString());
    }

    /// <summary>
    /// Resolves a union member CDDL name to the C# type name used in [JsonDerivedType].
    /// Union members that are themselves unions get their abstract base name;
    /// command results get the CommandResult suffix; all others get LocalName.
    /// </summary>
    private static string ResolveMemberTypeName(
        string cddlName,
        IReadOnlyDictionary<string, NodeKind> nodeKinds,
        EmitContext ctx)
    {
        if (nodeKinds.TryGetValue(cddlName, out NodeKind kind))
        {
            if (kind == NodeKind.CommandResult)
            {
                return ctx.ResolveClassName(cddlName, NamingConventions.CommandResultClassName(cddlName));
            }
        }

        return ctx.ResolveClassName(cddlName, NamingConventions.LocalName(cddlName));
    }

    private static List<PropSpec> GatherProperties(
        AstGroupNode group,
        string ownerCddlName,
        IReadOnlyDictionary<string, AstNode> byName,
        IReadOnlyDictionary<string, NodeKind> nodeKinds,
        EmitContext ctx,
        HashSet<string>? visited = null)
    {
        List<PropSpec> result = new();

        foreach (AstPropertyItem item in group.Properties)
        {
            if (item is AstPropertyEntry entry)
            {
                AddPropSpec(result, entry, ownerCddlName, byName, nodeKinds, ctx, visited);
            }

            // AstPropertyChoice: choice groups — skip for now (too complex to auto-generate)
        }

        return result;
    }

    private static void AddPropSpec(
        List<PropSpec> result,
        AstPropertyEntry entry,
        string ownerCddlName,
        IReadOnlyDictionary<string, AstNode> byName,
        IReadOnlyDictionary<string, NodeKind> nodeKinds,
        EmitContext ctx,
        HashSet<string>? visited)
    {
        // Unnamed entry with a single group ref = CDDL group inclusion (e.g. "include BaseType")
        // Flatten by recursively gathering the referenced group's properties.
        if (string.IsNullOrEmpty(entry.Name) &&
            entry.Type.Count == 1 &&
            entry.Type[0] is AstTypeGroupRef gr &&
            gr.Value is not ("Extensible" or "EmptyParams"))
        {
            visited ??= new HashSet<string>(StringComparer.Ordinal);
            if (visited.Add(gr.Value) &&
                byName.TryGetValue(gr.Value, out AstNode? refNode) &&
                refNode is AstGroupNode refGroup)
            {
                // Keep the outermost owner name so property overrides for that type apply
                result.AddRange(GatherProperties(refGroup, ownerCddlName, byName, nodeKinds, ctx, visited));
            }

            return;
        }

        // Skip remaining unnamed entries (Extensible, EmptyParams, etc.)
        if (string.IsNullOrEmpty(entry.Name))
        {
            return;
        }

        // Skip "method" and "params" (command/event structure fields, not data)
        if (entry.Name is "method" or "params" or "id")
        {
            return;
        }

        string jsonName = entry.Name;
        string csharpName = ctx.ResolvePropName(ownerCddlName, jsonName);
        bool isOptional = entry.Occurrence.N == 0;
        (string csType, bool isList, string listElem) = TypeResolver.Resolve(entry.Type, byName, nodeKinds);
        List<string> referencedCddlNames = TypeResolver.ReferencedNonTrivialCddlNames(entry.Type, byName, nodeKinds).Distinct().ToList();

        result.Add(new PropSpec(jsonName, csharpName, csType, !isOptional, isList, listElem, referencedCddlNames));
    }

    // -----------------------------------------------------------------------
    // Property emission: deserialization context (results, data, event args)
    // -----------------------------------------------------------------------
    private static void AppendDeserializationProperties(StringBuilder sb, List<PropSpec> props)
    {
        bool firstProp = true;
        foreach (PropSpec p in props)
        {
            if (!firstProp)
            {
                sb.AppendLine();
            }

            firstProp = false;

            if (p.IsList)
            {
                // Public IList<T> wrapping an internal List<T>
                sb.AppendLine($"    [JsonIgnore]");
                sb.AppendLine($"    public IList<{p.ListElementType}> {p.CSharpName} => this.Serializable{p.CSharpName}.AsReadOnly();");
                sb.AppendLine();
                if (p.IsRequired)
                {
                    sb.AppendLine($"    [JsonPropertyName(\"{p.JsonName}\")]");
                    sb.AppendLine($"    [JsonRequired]");
                    sb.AppendLine($"    [JsonInclude]");
                }
                else
                {
                    sb.AppendLine($"    [JsonPropertyName(\"{p.JsonName}\")]");
                    sb.AppendLine($"    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]");
                    sb.AppendLine($"    [JsonInclude]");
                }

                sb.AppendLine($"    internal List<{p.ListElementType}> Serializable{p.CSharpName} {{ get; set; }} = [];");
            }
            else if (p.IsRequired)
            {
                sb.AppendLine($"    [JsonPropertyName(\"{p.JsonName}\")]");
                sb.AppendLine($"    [JsonRequired]");
                sb.AppendLine($"    [JsonInclude]");

                // Keep '?' when CDDL union includes null — field is required to be present but value may be null
                if (p.CSharpType.EndsWith('?'))
                {
                    sb.AppendLine($"    public {p.CSharpType} {p.CSharpName} {{ get; internal set; }}");
                }
                else
                {
                    sb.AppendLine($"    public {p.CSharpType} {p.CSharpName} {{ get; internal set; }} = default!;");
                }
            }
            else
            {
                // Optional: type already has '?' from TypeResolver when hasNull
                string nullableType = p.CSharpType.EndsWith('?') ? p.CSharpType : p.CSharpType + "?";
                sb.AppendLine($"    [JsonPropertyName(\"{p.JsonName}\")]");
                sb.AppendLine($"    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]");
                sb.AppendLine($"    [JsonInclude]");
                sb.AppendLine($"    public {nullableType} {p.CSharpName} {{ get; internal set; }}");
            }
        }

        if (props.Count > 0)
        {
            sb.AppendLine();
        }
    }

    // -----------------------------------------------------------------------
    // Property emission: command parameters context (serialization)
    // -----------------------------------------------------------------------
    private static void AppendCommandParamsProperties(StringBuilder sb, List<PropSpec> props)
    {
        bool firstProp = true;
        foreach (PropSpec p in props)
        {
            if (!firstProp)
            {
                sb.AppendLine();
            }

            firstProp = false;

            if (p.IsList)
            {
                // Required list: direct property, set in constructor
                // Optional list: nullable, omitted when null
                if (p.IsRequired)
                {
                    sb.AppendLine($"    [JsonPropertyName(\"{p.JsonName}\")]");
                    sb.AppendLine($"    [JsonIgnore]");
                    sb.AppendLine($"    public IList<{p.ListElementType}> {p.CSharpName} => this.Serializable{p.CSharpName}.AsReadOnly();");
                    sb.AppendLine();
                    sb.AppendLine($"    [JsonPropertyName(\"{p.JsonName}\")]");
                    sb.AppendLine($"    [JsonInclude]");
                    sb.AppendLine($"    internal List<{p.ListElementType}> Serializable{p.CSharpName} {{ get; set; }} = [];");
                }
                else
                {
                    sb.AppendLine($"    [JsonPropertyName(\"{p.JsonName}\")]");
                    sb.AppendLine($"    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]");
                    sb.AppendLine($"    public List<{p.ListElementType}>? {p.CSharpName} {{ get; set; }}");
                }
            }
            else if (p.IsRequired)
            {
                sb.AppendLine($"    [JsonPropertyName(\"{p.JsonName}\")]");
                string bareType = p.CSharpType.TrimEnd('?');
                sb.AppendLine($"    public {bareType} {p.CSharpName} {{ get; set; }}");
            }
            else
            {
                string nullableType = p.CSharpType.EndsWith('?') ? p.CSharpType : p.CSharpType + "?";
                sb.AppendLine($"    [JsonPropertyName(\"{p.JsonName}\")]");
                sb.AppendLine($"    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]");
                sb.AppendLine($"    public {nullableType} {p.CSharpName} {{ get; set; }}");
            }
        }

        if (props.Count > 0)
        {
            sb.AppendLine();
        }
    }


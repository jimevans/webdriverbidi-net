        string JsonName,
        string CSharpName,
        string CSharpType,
        bool IsRequired,
        bool IsList,
        string ListElementType,
        IReadOnlyList<string> ReferencedCddlNames);

    // -----------------------------------------------------------------------
    // Emit context: carries per-run config data to avoid threading many params
    // -----------------------------------------------------------------------
    private sealed class EmitContext
    {
        private static readonly IReadOnlyDictionary<string, string> EmptyTypeNames =
            new Dictionary<string, string>(StringComparer.Ordinal);

        private static readonly IReadOnlyDictionary<string, IReadOnlyDictionary<string, string>> EmptyPropNames =
            new Dictionary<string, IReadOnlyDictionary<string, string>>(StringComparer.Ordinal);

        public EmitContext(GeneratorConfig? config)
        {
            this.SkipSet = config?.SkipGeneration is { Count: > 0 } skip
                ? new HashSet<string>(skip, StringComparer.Ordinal)
                : [];
            this.TypeNames = config?.NameMap.Types ?? EmptyTypeNames;
            this.PropNames = config?.NameMap.Properties ?? EmptyPropNames;
        }

        public HashSet<string> SkipSet { get; }

        public IReadOnlyDictionary<string, string> TypeNames { get; }

        public IReadOnlyDictionary<string, IReadOnlyDictionary<string, string>> PropNames { get; }

        /// <summary>
        /// Returns the C# class name to use, applying any configured type name override.
        /// Falls back to <paramref name="derivedName"/> when no override is present.
        /// </summary>
        public string ResolveClassName(string cddlName, string derivedName)
            => this.TypeNames.TryGetValue(cddlName, out string? name) ? name : derivedName;

        /// <summary>
        /// Returns the C# property name for the given JSON property on the given owner type,
        /// applying any configured property name override. Falls back to PascalCase.
        /// </summary>
        public string ResolvePropName(string ownerCddlName, string jsonName)
        {
            if (this.PropNames.TryGetValue(ownerCddlName, out IReadOnlyDictionary<string, string>? typeProps) &&
                typeProps.TryGetValue(jsonName, out string? overrideName))
            {
                return overrideName;
            }

            return PascalCase(jsonName);
        }
    }

    // -----------------------------------------------------------------------
    // Phase 4: Command parameters with fields
    // -----------------------------------------------------------------------
    private static (string RelativePath, string Code) EmitCommandParameters(
        CommandDef cmd,
        AstGroupNode paramsGroup,
        SpecModel model,
        IReadOnlyDictionary<string, AstNode> byName,
        EmitContext ctx)
    {
        string csharpName = ctx.ResolveClassName(cmd.AstNode.Name, NamingConventions.CommandParamsClassName(cmd.AstNode.Name));
        string resultCsharpName = ctx.ResolveClassName(cmd.ResultTypeName, NamingConventions.CommandResultClassName(cmd.ResultTypeName));
        string ns = NamingConventions.Namespace(cmd.AstNode.Name);
        string subdir = NamingConventions.Subdir(cmd.AstNode.Name);
        string fileName = csharpName + ".cs";
        string relativePath = subdir.Length > 0 ? $"{subdir}/{fileName}" : fileName;

        List<PropSpec> props = GatherProperties(paramsGroup, cmd.ParamsTypeName, byName, model.NodeKinds, ctx);
        IReadOnlyList<string> usings = GatherUsings(props, ns, isCommandParams: true);

        StringBuilder sb = new();
        sb.AppendFormat(CopyrightHeader, fileName);
        sb.AppendLine();
        sb.AppendLine($"namespace {ns};");
        sb.AppendLine();
        AppendUsings(sb, usings);
        sb.AppendLine($"public class {csharpName} : CommandParameters<{resultCsharpName}>");
        sb.AppendLine("{");

        // Constructor with required fields as parameters
        List<PropSpec> required = props.Where(p => p.IsRequired && !p.IsList).ToList();
        List<PropSpec> requiredLists = props.Where(p => p.IsRequired && p.IsList).ToList();
        List<PropSpec> allRequired = props.Where(p => p.IsRequired).ToList();

        if (allRequired.Count > 0)
        {
            string ctorParams = string.Join(", ", allRequired.Select(p => $"{p.CSharpType} {CamelCase(p.CSharpName)}"));
            sb.AppendLine($"    public {csharpName}({ctorParams})");
            sb.AppendLine("    {");
            foreach (PropSpec p in allRequired)
            {
                if (p.IsList)
                {
                    sb.AppendLine($"        this.Serializable{p.CSharpName} = {CamelCase(p.CSharpName)};");
                }
                else
                {
                    sb.AppendLine($"        this.{p.CSharpName} = {CamelCase(p.CSharpName)};");
                }
            }

            sb.AppendLine("    }");
        }
        else
        {
            sb.AppendLine($"    public {csharpName}()");
            sb.AppendLine("    {");
            sb.AppendLine("    }");
        }

        sb.AppendLine();
        sb.AppendLine("    [JsonIgnore]");
        sb.AppendLine($"    public override string MethodName => \"{cmd.MethodLiteral}\";");
        sb.AppendLine();
        AppendCommandParamsProperties(sb, props);
        sb.AppendLine("}");
        return (relativePath, sb.ToString());
    }


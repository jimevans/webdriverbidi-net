    // Phase 4: Group command result (has its own fields)
    // -----------------------------------------------------------------------
    private static (string RelativePath, string Code) EmitGroupCommandResult(
        CommandResultDef r,
        AstGroupNode groupNode,
        SpecModel model,
        IReadOnlyDictionary<string, AstNode> byName,
